import { useEffect } from 'react'
import Lenis from 'lenis'

const REDUCED_MOTION = '(prefers-reduced-motion: reduce)'

/**
 * Инерционная прокрутка всей страницы.
 *
 * Колесо и трекпад перестают двигать полосу рывками на фиксированный шаг:
 * Lenis перехватывает wheel и догоняет цель интерполяцией, поэтому длинная
 * страница (на 390px её высота около 5800px) читается как одно движение, а не
 * как серия щелчков.
 *
 * Тач намеренно оставлен родным (syncTouch по умолчанию false): на телефоне
 * инерцию уже считает система, и подмена своей даёт на iOS заметное запаздывание
 * под пальцем. Так что на телефоне эффекта нет — он только для колеса и
 * трекпада, а это ровно те устройства, где родная прокрутка ступенчата.
 *
 * Якорные ссылки (шапка, «пропустить к меню», билеты в герое) намеренно
 * оставлены браузеру — опцию anchors не включаем. Она заставляет Lenis вести
 * переход самому, а он на время прогона держит isScrolling === 'smooth' и в
 * этом состоянии отбрасывает чужие события прокрутки (Lenis.onNativeScroll),
 * каждый кадр возвращая полосу к своей цели. Пока идёт переход, у пользователя
 * молча отнимают End, Home, PageDown, пробел, перетаскивание ползунка и переход
 * по найденному через Ctrl+F: нажатие срабатывает и тут же затирается. Сверх
 * того Lenis.onClick не смотрит ни на модификаторы, ни на кнопку мыши, поэтому
 * Cmd+клик по «Меню» открывал бы вкладку — и заодно уводил текущую.
 *
 * Родной переход всего этого лишён и уже сглажен: html { scroll-behavior:
 * smooth } в styles.css. Со своей прокруткой Lenis его не путает — свои кадры он
 * пишет через scrollTo({ behavior: 'instant' }), а чужую прокрутку, раз она не
 * его, спокойно догоняет. Так что колесо получает инерцию, а якоря остаются
 * ровно такими, какими были до Lenis.
 *
 * prefers-reduced-motion выключает эффект целиком, причём на лету: настройку
 * меняют, не перезагружая вкладку, и подписка на mq это отслеживает. Тогда
 * экземпляра просто нет, а родное сглаживание гасит блок в конце styles.css.
 */
export function useSmoothScroll() {
  useEffect(() => {
    const mq = window.matchMedia(REDUCED_MOTION)
    let lenis: Lenis | undefined

    const sync = () => {
      if (mq.matches) {
        lenis?.destroy()
        lenis = undefined
        return
      }
      lenis ??= new Lenis({
        autoRaf: true,
      })
    }

    sync()
    mq.addEventListener('change', sync)
    return () => {
      mq.removeEventListener('change', sync)
      lenis?.destroy()
    }
  }, [])
}
